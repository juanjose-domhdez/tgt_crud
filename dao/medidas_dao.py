class Medida:

    def __init__(
        self,
        id_medida=None,
        id_pedido=None,
        pecho=0.0,
        cintura=0.0,
        hombros=0.0,
        manga=0.0,
        largo_pantalon=0.0,
    ):
        self.id_medida = id_medida
        self.id_pedido = id_pedido
        self.pecho = pecho
        self.cintura = cintura
        self.hombros = hombros
        self.manga = manga
        self.largo_pantalon = largo_pantalon